"""Generate docs/API.md (from the live OpenAPI schema) and docs/MODEL_RESULTS.md (from the stored
model cards / evaluation records). Numbers in the docs therefore are the measured ones."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("FS_DATABASE_URL", "sqlite://")

ROLE = {"viewer": "any signed-in user", "inspector": "inspector+", "engineer": "engineer+", "admin": "admin"}


def api_md() -> str:
    from app.main import app

    spec = app.openapi()
    out = ["# API reference", "", "Base path `/api`. Interactive docs: `/docs` (Swagger) and `/redoc`; machine-readable schema: `/openapi.json`.", "",
           "Authentication: `POST /api/auth/login` returns a bearer token; send `Authorization: Bearer <token>` on every other call.",
           "Errors are JSON `{\"detail\": ...}`; validation errors (422) also carry an `errors` list. Roles: viewer < inspector < engineer < admin.", ""]
    by_tag: dict[str, list] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by_tag.setdefault((op.get("tags") or ["other"])[0], []).append((path, method.upper(), op))
    for tag, items in by_tag.items():
        out += [f"## {tag}", "", "| Method | Path | Summary | Parameters / body |", "|---|---|---|---|"]
        for path, method, op in items:
            params = [p["name"] + ("*" if p.get("required") else "") for p in op.get("parameters", []) if p["in"] in ("query", "path")]
            body = op.get("requestBody", {}).get("content", {})
            if body:
                ctype = next(iter(body))
                ref = body[ctype]["schema"].get("$ref", "").split("/")[-1]
                props = spec["components"]["schemas"].get(ref, {}).get("properties", {})
                req = set(spec["components"]["schemas"].get(ref, {}).get("required", []))
                kind = "form" if "multipart" in ctype else "json"
                params.append(f"{kind}: " + ", ".join(k + ("*" if k in req else "") for k in props))
            doc = (op.get("description") or op.get("summary") or "").strip().split("\n")[0]
            out.append(f"| {method} | `{path}` | {doc} | {'; '.join(params)} |")
        out.append("")
    out += ["`*` = required.", ""]
    return "\n".join(out)


def models_md() -> str:
    root = ROOT / "data" / "models"
    out = ["# Model documentation and measured results", "",
           "Generated by `scripts/gen_docs.py` from the model cards and evaluation records in `data/models/`. "
           "Every number was measured on a held-out split by `backend/scripts/benchmarks.py`; none is copied from a paper.", ""]
    evals = [e for p in sorted((root / "evaluations").glob("*.json")) for e in json.loads(p.read_text())]

    def g(d, *ks):
        for k in ks:
            d = d.get(k) if isinstance(d, dict) else None
        return d

    out += ["## Summary", "", "| Model | Material / dataset | Test n | Result (test split) |", "|---|---|---|---|"]
    for e in evals:
        m = e["metrics"]
        if g(m, "test", "auroc") is not None:
            t = m["test"]
            res = f"AUROC {t['auroc']}, F1 {t.get('f1')}, precision {t.get('precision')}, recall {t.get('recall')} (95% CI {t.get('recall_ci95')}), FPR {t.get('false_positive_rate')}, FNR {t.get('false_negative_rate')}"
            if g(m, "test", "calibration", "ece") is not None:
                res += f", ECE {m['test']['calibration']['ece']}"
        elif "localization" in m:
            res = (f"localization P {m['localization']['precision']} / R {m['localization']['recall']} / F1 {m['localization']['f1']}; "
                   f"with correct class F1 {m['class_aware']['f1']}; {m['localization']['false_alarms_per_image']} false alarms per image")
        elif "test_pixel_strict" in m:
            res = f"pixel F1 {m['test_pixel_strict']['pixel_f1']} (IoU {m['test_pixel_strict']['iou']}); with 2 px tolerance F1 {m['test_pixel_tolerant']['pixel_f1']}"
        else:
            res = f"accuracy {g(m, 'test', 'accuracy')} (95% CI {g(m, 'test', 'accuracy_ci95')})"
        out.append(f"| `{e['model']}` {e['version']} | {e['material']} / {e['dataset']} | {e['n']} | {res} |")
    out.append("")
    for e in evals:
        m = e["metrics"]
        tri = m.get("test_triage")
        if tri:
            out += [f"### Three-way decision of `{e['model']}` on the test split", "",
                    f"Thresholds chosen on validation only (pass <= {tri['t_low']}, reject >= {tri['t_high']}). Of {tri['n']} test images: "
                    f"{tri['auto_pass']} auto-passed, {tri['auto_defective']} auto-rejected, {tri['sent_to_review']} sent to review "
                    f"({tri['review_rate']:.1%}). Escaped defects: {tri['escaped_defects']} (95% CI of the escape rate {tri['escape_rate_ci95']}); "
                    f"false rejects: {tri['false_rejects']} (95% CI {tri['false_reject_ci95']}). "
                    f"Accuracy of automatic decisions {tri['auto_decision_accuracy']} (95% CI {tri['auto_decision_accuracy_ci95']}).", ""]
            if m.get("operating_points"):
                out += ["| Validation tolerance | Auto-pass | Auto-defective | Sent to review | Escaped defects (95% CI of rate) | False rejects (95% CI of rate) |", "|---|---|---|---|---|---|"]
                for o in m["operating_points"]:
                    t = o["test"]
                    out.append(f"| {o['validation_tolerance']:.0%}{' **(in use)**' if o['shipped'] else ''} | {t['auto_pass']} | {t['auto_defective']} | "
                               f"{t['sent_to_review']} ({t['review_rate']:.0%}) | {t['escaped_defects']} {t['escape_rate_ci95']} | {t['false_rejects']} {t['false_reject_ci95']} |")
                out.append("")
            pd = m.get("test_per_defect") or {}
            if pd:
                out += ["| Defect | Test images | Detected at p>=0.5 | Caught or sent to review |", "|---|---|---|---|"]
                out += [f"| {k} | {v['support']} | {v['recall_at_0.5']} (95% CI {v['recall_ci95']}) | {v['caught_or_reviewed_rate']} |" for k, v in pd.items()] + [""]
        if m.get("cross_validation"):
            cv = m["cross_validation"]
            out += [f"`{e['model']}` {cv['folds']}-fold cross-validated AUROC: {cv['auroc_mean']} ± {cv['auroc_std']} (folds {cv['auroc_per_fold']}).", ""]
        if g(m, "test_defect_type", "accuracy") is not None:
            dt = m["test_defect_type"]
            out += [f"`{e['model']}` defect-type classification on test defect images: accuracy {dt['accuracy']} (95% CI {dt['accuracy_ci95']}), macro-F1 {dt['macro_f1']}; "
                    f"pixel F1 {g(m, 'test_pixel', 'pixel_f1')}, IoU {g(m, 'test_pixel', 'iou')}.", ""]
        if m.get("per_defect"):
            out += [f"### Per-defect results of `{e['model']}`", "", "| Defect | Test defects | Recall | 95% CI | Precision |", "|---|---|---|---|---|"]
            out += [f"| {k} | {v['support']} | {v['recall']} | {v['recall_ci95']} | {v['precision']} |" for k, v in m["per_defect"].items()] + [""]
    out += ["## The 99.9% target", "",
            "No model here reaches 99.9%, and the test sets are too small to demonstrate it even for a perfect model: "
            "with zero errors, the upper 95% bound on the error rate is roughly 3/n, so showing an error rate below 0.1% needs about "
            "3,000 error-free test samples *per class*, from the production camera and lighting. The platform is built to get there "
            "honestly (review band, calibration, drift monitoring, active learning, per-version evaluation records) rather than to claim it.", "",
            "## Model cards", ""]
    for card_path in sorted(root.glob("*/*/card.json")):
        c = json.loads(card_path.read_text())
        out += [f"### `{c['name']}` {c['version']} ({c.get('kind')})", "",
                f"* **Architecture:** {c.get('architecture')}", f"* **Material:** {c.get('material', '-')}", f"* **Data:** {c.get('dataset')}",
                f"* **Splits:** `{json.dumps(c.get('splits'))}`"]
        if c.get("trained_on"):
            out.append(f"* **Trained on:** {c['trained_on']}")
        if c.get("training"):
            t = {k: v for k, v in c["training"].items() if k != "loss_history"}
            out.append(f"* **Training:** `{json.dumps(t)}`")
        out += ["* **Limitations:**"] + [f"  * {x}" for x in c.get("limitations", [])] + [""]
    return "\n".join(out)


if __name__ == "__main__":
    (ROOT / "docs" / "API.md").write_text(api_md())
    (ROOT / "docs" / "MODEL_RESULTS.md").write_text(models_md())
    print("wrote docs/API.md, docs/MODEL_RESULTS.md")
